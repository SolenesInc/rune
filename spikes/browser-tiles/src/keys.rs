use rune::PhysicalKeyCode as K;

/// The macOS virtual key code and the Windows virtual key code CEF wants for a physical key.
pub fn codes(key: K) -> Option<(i32, i32)> {
    Some(match key {
        K::KeyA => (0x00, 0x41), K::KeyS => (0x01, 0x53), K::KeyD => (0x02, 0x44), K::KeyF => (0x03, 0x46),
        K::KeyH => (0x04, 0x48), K::KeyG => (0x05, 0x47), K::KeyZ => (0x06, 0x5A), K::KeyX => (0x07, 0x58),
        K::KeyC => (0x08, 0x43), K::KeyV => (0x09, 0x56), K::KeyB => (0x0B, 0x42), K::KeyQ => (0x0C, 0x51),
        K::KeyW => (0x0D, 0x57), K::KeyE => (0x0E, 0x45), K::KeyR => (0x0F, 0x52), K::KeyY => (0x10, 0x59),
        K::KeyT => (0x11, 0x54), K::Digit1 => (0x12, 0x31), K::Digit2 => (0x13, 0x32), K::Digit3 => (0x14, 0x33),
        K::Digit4 => (0x15, 0x34), K::Digit6 => (0x16, 0x36), K::Digit5 => (0x17, 0x35), K::Equal => (0x18, 0xBB),
        K::Digit9 => (0x19, 0x39), K::Digit7 => (0x1A, 0x37), K::Minus => (0x1B, 0xBD), K::Digit8 => (0x1C, 0x38),
        K::Digit0 => (0x1D, 0x30), K::BracketRight => (0x1E, 0xDD), K::KeyO => (0x1F, 0x4F), K::KeyU => (0x20, 0x55),
        K::BracketLeft => (0x21, 0xDB), K::KeyI => (0x22, 0x49), K::KeyP => (0x23, 0x50), K::Enter => (0x24, 0x0D),
        K::KeyL => (0x25, 0x4C), K::KeyJ => (0x26, 0x4A), K::Quote => (0x27, 0xDE), K::KeyK => (0x28, 0x4B),
        K::Semicolon => (0x29, 0xBA), K::Backslash => (0x2A, 0xDC), K::Comma => (0x2B, 0xBC), K::Slash => (0x2C, 0xBF),
        K::KeyN => (0x2D, 0x4E), K::KeyM => (0x2E, 0x4D), K::Period => (0x2F, 0xBE), K::Tab => (0x30, 0x09),
        K::Space => (0x31, 0x20), K::Backquote => (0x32, 0xC0), K::Backspace => (0x33, 0x08), K::Escape => (0x35, 0x1B),
        K::Delete => (0x75, 0x2E), K::Home => (0x73, 0x24), K::End => (0x77, 0x23), K::PageUp => (0x74, 0x21),
        K::PageDown => (0x79, 0x22), K::ArrowLeft => (0x7B, 0x25), K::ArrowRight => (0x7C, 0x27),
        K::ArrowDown => (0x7D, 0x28), K::ArrowUp => (0x7E, 0x26),
        _ => return None,
    })
}

/// The character AppKit gives a non-text key; CEF reads a key event with no character as a
/// modifier change.
pub fn mac_char(native: i32) -> u16 {
    match native {
        0x24 => 0x0D, 0x30 => 0x09, 0x33 => 0x7F, 0x35 => 0x1B, 0x75 => 0xF728, 0x73 => 0xF729,
        0x77 => 0xF72B, 0x74 => 0xF72C, 0x79 => 0xF72D, 0x7B => 0xF702, 0x7C => 0xF703,
        0x7D => 0xF701, 0x7E => 0xF700,
        _ => 0,
    }
}
